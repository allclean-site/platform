-- Закрываем хранилище фотографий помещений.
--
-- Было: бакет `calc-uploads` публичный. Список файлов посторонним недоступен, но
-- кто знает адрес — открывает снимок чужой квартиры в любой момент и без срока.
-- А адрес угадывался: в имени файла стояло время отправки (оно совпадает со временем
-- заявки) и пять символов Math.random(). Это фотографии жилья людей — так их хранить
-- нельзя (ст. 29 Закона № 195/2024: меры, соразмерные риску).
--
-- Стало: бакет закрыт, читать его может только служебный ключ. Сайт кладёт в заявку
-- ПУТЬ файла, а ссылку на неделю подписывает сервер при отправке уведомления;
-- кабинет подписывает свою на час, когда сотрудник открывает заявку.
--
-- ⚠ ПОРЯДОК ВАЖЕН. Сначала выкатите новый код сайта и кабинета — он понимает и пути,
-- и старые полные адреса. Затем выполните этот файл целиком, одним запуском:
-- шаг 1 переводит старые заявки на пути, шаг 2 закрывает бакет. Если поменять шаги
-- местами, фотографии старых заявок перестанут открываться до выполнения шага 1.

begin;

-- ── Шаг 1. Старые заявки: полный публичный адрес → путь внутри бакета ────────────
-- В `notes` лежит JSON вида {"selections":…, "photos":["https://…/object/public/calc-uploads/apartments/x.jpg"]}.
-- Оставляем от каждого адреса только «apartments/x.jpg».
update public.site_leads
set notes = regexp_replace(notes, 'https?://[^"]*?/storage/v1/object/public/calc-uploads/', '', 'g')
where notes like '%/object/public/calc-uploads/%';

-- ── Шаг 2. Бакет становится закрытым ────────────────────────────────────────────
update storage.buckets set public = false where id = 'calc-uploads';

-- Права не расширяем: анонимной роли по-прежнему разрешена ТОЛЬКО запись — посетитель
-- должен уметь приложить фотографию к заявке, но не читать чужие. Чтения для anon нет
-- вовсе, поэтому ссылку выдаёт сервер, подписывая её служебным ключом.
drop policy if exists "anon upload calc-uploads" on storage.objects;
create policy "anon upload calc-uploads"
  on storage.objects for insert to anon
  with check (bucket_id = 'calc-uploads');

commit;

